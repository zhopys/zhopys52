public static class ReportKpiLabels
{
    public static (string Label, string Hint) Get(string key) => key switch
    {
        "revenue" => ("Выручка", "Все поступления за выбранный период (доходные операции)"),
        "opex" => ("Операционные расходы", "Текущие затраты на работу бизнеса: зарплаты, аренда, услуги, закупки (без крупных вложений в активы)"),
        "capex" => ("Капитальные расходы", "Вложения в долгосрочные активы: оборудование, техника, капитальный ремонт"),
        "netProfit" => ("Чистая прибыль", "Выручка минус все расходы за период"),
        "ebitda" => ("Операционная прибыль (EBITDA)", "Прибыль от основной деятельности до налогов, процентов и амортизации"),
        "roi" => ("Рентабельность проектов", "Средняя целевая доходность активных проектов, %"),
